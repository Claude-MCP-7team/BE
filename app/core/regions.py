def _gyeonggi_names() -> dict[str, str]:
    """코드 → 이름. 구 있는 시는 시 코드(끝자리 0)에도 시 이름을 단다."""
    out = {code: name for name, code in GYEONGGI_CODES.items()}
    for name, code in GYEONGGI_CODES.items():
        if " " in name:
            out.setdefault(code[:4] + "0", name.split()[0])
    return out


