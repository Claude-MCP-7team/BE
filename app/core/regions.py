def describe_region(code: str) -> str:
    """'경기 부천시(41190)' · '인천 28155' · '12110' — 아는 만큼만 붙인다."""
    sido = SIDO_NAMES.get(code[:2])
    name = _NAMES.get(code)
    if name:
        return f"{sido} {name}({code})"
    if sido:
        return f"{sido} {code}"
    return code
